// La Kurwa - turning data back into the editable .js files (used by the editor and the in-game map export)
'use strict';

LK.ser = {
  // compact JS object literal: { name: "x", price: 3 }
  obj(v) {
    if (Array.isArray(v)) return '[' + v.map(x => LK.ser.obj(x)).join(', ') + ']';
    if (v && typeof v === 'object') {
      const keys = Object.keys(v).filter(k => v[k] !== undefined && v[k] !== null && v[k] !== '');
      return '{ ' + keys.map(k => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)) + ': ' + LK.ser.obj(v[k])).join(', ') + ' }';
    }
    return JSON.stringify(v);
  },
  table(name, tbl) {
    return name + ' = {\n' + Object.keys(tbl).map(k => '  ' + (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)) + ': ' + LK.ser.obj(tbl[k])).join(',\n') + '\n};\n';
  },
  furnitureFile(furn) {
    return '// La Kurwa - furniture & devices. Edit here or with editor.html (Furniture tab).\n' +
      '// sprite: graphics base name (see data/sprites.js), dirs: one suffix per rotation, block: blocks walking,\n' +
      '// tags: seat|counter|table|cook|fresh|aid|light|decor|music|flat|toilet|storage, tech: skill to build/repair,\n' +
      '// anchor: auto|tile|bottom, scale (bottom-anchored), big (tile-anchored), dx/dy: pixel offsets, icon: item icon overlay,\n' +
      '// light: light radius in tiles, speed: cooking speed, vendor: merchant vendor skill needed, nosell: world decoration only,\n' +
      '// placement: furniture goes only inside the bar (B/K/S rooms); outdoor: only outside the bar instead. tag rent: a tent guests can rent (js/tents.js). tag ratAltar: js/rats.js.\n' +
      LK.ser.table('LK.FURNITURE', furn);
  },
  itemsFile(ing, goods) {
    return '// La Kurwa - ingredients and other goods. Edit here or with editor.html (Items tab). Prices in Mariuszki.\n' +
      '// kind: drink|food, type: what clients like (free text), alcohol: drunkenness per unit, vendor: vendor skill to unlock, icon: item icon key\n' +
      LK.ser.table('LK.INGREDIENTS', ing) + '\n' +
      '// weapon: damage bonus, desc: shop description\n' +
      LK.ser.table('LK.GOODS', goods);
  },
  mapFile(def, id) {
    const doors = [], windows = [], eo = {};
    for (const [k, v] of Object.entries(def.edgeOverride || {})) {
      const [x, y, side] = k.split(',');
      if (v === 'door') doors.push({ x: +x, y: +y, side });
      else if (v === 'window') windows.push({ x: +x, y: +y, side });
      else eo[k] = v;
    }
    (def.doors || []).forEach(d => doors.push(d));
    (def.windows || []).forEach(d => windows.push(d));
    const rows = a => a.map(r => "    '" + r + "'").join(',\n');
    const list = a => a.length ? '\n    ' + a.map(o => LK.ser.obj(o)).join(',\n    ') + '\n  ' : '';
    return '// =====================================================================\n' +
      '//  La Kurwa map "' + (def.name || id) + '"  (edit by hand or with editor.html)\n' +
      '//  Every row of `ground` and `rooms` must have the same length.\n' +
      '//  ground:  ' + Object.entries(LK.GROUND_NAMES || {}).map(([k, n]) => k + ' ' + n).join(',  ') + '\n' +
      '//  rooms:   . outside   B bar room   K kitchen   S storage (required!)   X ruin\n' +
      '//  floors (optional, inside rooms): . room default   ' + Object.entries(LK.FLOORS).map(([k, f]) => k + ' ' + f.name.toLowerCase()).join(', ') + '\n' +
      '//  doors / windows: { x, y, side }  side = N | W (S/E also accepted)\n' +
      '//  edgeOverride: { "x,y,N|W": "wall" | "none" | "door" | "window" | a wall piece sprite, e.g. "stoneWallArchway" (LK.WALL_PIECES) }\n' +
      '//  objects: { type (data/furniture.js), x, y, rot (0-3) }\n' +
      '//  route: road rows that travellers walk along (west <-> east)\n' +
      '// =====================================================================\n' +
      'LK.MAPS = LK.MAPS || {};\n' +
      'LK.MAPS[' + JSON.stringify(id) + '] = {\n' +
      '  name: ' + JSON.stringify(def.name || id) + ',\n' +
      '  ground: [\n' + rows(def.ground) + '\n  ],\n' +
      '  rooms: [\n' + rows(def.rooms) + '\n  ],\n' +
      (def.floors && def.floors.some(r => /[^.]/.test(r)) ? '  floors: [\n' + rows(def.floors) + '\n  ],\n' : '') +
      '  doors: [' + list(doors) + '],\n' +
      '  windows: [' + list(windows) + '],\n' +
      '  edgeOverride: ' + LK.ser.obj(eo) + ',\n' +
      '  objects: [' + list((def.objects || []).map(o => ({ type: o.type, x: o.x, y: o.y, rot: o.rot || undefined }))) + '],\n' +
      '  route: ' + LK.ser.obj(def.route) + ',\n' +
      '  playerStart: ' + LK.ser.obj(def.playerStart) + ',\n' +
      '  merchantSpot: ' + LK.ser.obj(def.merchantSpot) + '\n' +
      '};\n';
  },
  mapIndexFile(ids) {
    return '// List of map files in this folder (maps/<id>.js). Maintained by editor.html.\nLK.MAP_FILES = ' + JSON.stringify(ids) + ';\n';
  },
  spritesFile(sprites, atlas) {
    return '// GENERATED by tools/make_sprite_index.py (or the editor). Graphics in gfx/Isometric, gfx/custom and fallback folders.\n' +
      'LK.SPRITES = {\n' + Object.keys(sprites).sort().map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(sprites[k])).join(',\n') + '\n};\n' +
      'LK.ICON_ATLAS = ' + JSON.stringify(atlas) + ';\n';
  }
};

// read a map from text: either a maps/*.js file (LK.MAPS['id'] = {...}) or plain JSON
LK.parseMapText = function (txt) {
  let def = null;
  if (/LK\.MAPS\s*\[/.test(txt)) {
    const sandbox = { MAPS: {} };
    // the file only assigns object literals; evaluate it against a throw-away LK
    new Function('LK', txt)(sandbox);
    const ids = Object.keys(sandbox.MAPS);
    if (!ids.length) throw new Error('no LK.MAPS[...] entry found');
    def = sandbox.MAPS[ids[0]]; def._id = ids[0];
  } else def = JSON.parse(txt.replace(/^[^{]*/, '').replace(/;?\s*$/, ''));
  if (!def.ground || !def.rooms) throw new Error('missing ground/rooms');
  return def;
};

// ---------- minimal ZIP writer (stored, no compression) ----------
// entries: [{ name: 'game/data/items.js', bytes: Uint8Array }] -> Uint8Array of a valid .zip file
LK.crc32 = (() => {
  const T = new Uint32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; T[n] = c >>> 0; }
  return bytes => { let c = 0xFFFFFFFF; for (let i = 0; i < bytes.length; i++) c = T[(c ^ bytes[i]) & 255] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; };
})();
LK.zipFiles = function (entries, date) {
  const enc = new TextEncoder(), d = date || new Date();
  const dosTime = (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1);
  const dosDate = ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate();
  const parts = [], central = [];
  let offset = 0;
  for (const e of entries) {
    const name = enc.encode(e.name), data = e.bytes, crc = LK.crc32(data);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true); local.setUint16(4, 20, true); local.setUint16(6, 0x0800, true);   // UTF-8 names
    local.setUint16(8, 0, true); local.setUint16(10, dosTime, true); local.setUint16(12, dosDate, true);
    local.setUint32(14, crc, true); local.setUint32(18, data.length, true); local.setUint32(22, data.length, true);
    local.setUint16(26, name.length, true); local.setUint16(28, 0, true);
    parts.push(new Uint8Array(local.buffer), name, data);
    const cen = new DataView(new ArrayBuffer(46));
    cen.setUint32(0, 0x02014b50, true); cen.setUint16(4, 20, true); cen.setUint16(6, 20, true); cen.setUint16(8, 0x0800, true);
    cen.setUint16(10, 0, true); cen.setUint16(12, dosTime, true); cen.setUint16(14, dosDate, true);
    cen.setUint32(16, crc, true); cen.setUint32(20, data.length, true); cen.setUint32(24, data.length, true);
    cen.setUint16(28, name.length, true); cen.setUint32(42, offset, true);
    central.push(new Uint8Array(cen.buffer), name);
    offset += 30 + name.length + data.length;
  }
  const cenSize = central.reduce((a, p) => a + p.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true); end.setUint16(8, entries.length, true); end.setUint16(10, entries.length, true);
  end.setUint32(12, cenSize, true); end.setUint32(16, offset, true);
  const all = parts.concat(central, [new Uint8Array(end.buffer)]);
  const out = new Uint8Array(all.reduce((a, p) => a + p.length, 0));
  let o = 0; for (const p of all) { out.set(p, o); o += p.length; }
  return out;
};
